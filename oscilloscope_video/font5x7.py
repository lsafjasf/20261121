FONT: dict[str, tuple[str, ...]] = {
    character: tuple(rows.split("/")) for character, rows in _GLYPH_TEXT.items()
}
GLYPH_WIDTH = 5
GLYPH_HEIGHT = 7
FALLBACK = FONT["?"]


def glyph(character: str) -> tuple[str, ...]:
    return FONT.get(character, FALLBACK)


def display_unit(unit: str) -> str:
    """Keep the exact unit where possible, replacing unsupported glyphs."""

    replacements = {"\u00b0": "", "\u00b1": "+/-", "\u03a9": "\u03a9"}
    return "".join(replacements.get(character, character) for character in unit)


def text_width(text: str, scale: int, spacing: int | None = None) -> int:
    if not text:
        return 0
    gap = scale if spacing is None else spacing
    return len(text) * GLYPH_WIDTH * scale + (len(text) - 1) * gap
